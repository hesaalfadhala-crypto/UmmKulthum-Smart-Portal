create function documentation_private.guard_insert() returns trigger language plpgsql set search_path='' as $$
begin
 if new.deleted_at is not null or new.deleted_by is not null or new.deleted_by_name is not null or new.deletion_version<>0 then raise exception 'لا يمكن إنشاء تقرير محذوف أو تزوير سجل الحذف.';end if;
 new.academic_year:=coalesce(nullif(new.details->>'academicYear',''),case when extract(month from coalesce(new.activity_date,current_date))>=9 then extract(year from coalesce(new.activity_date,current_date))::int::text||'-'||(extract(year from coalesce(new.activity_date,current_date))::int+1)::text else (extract(year from coalesce(new.activity_date,current_date))::int-1)::text||'-'||extract(year from coalesce(new.activity_date,current_date))::int::text end);
 if new.academic_year!~'^20[0-9]{2}-20[0-9]{2}$' then raise exception 'العام الدراسي غير صالح.';end if;
 return new;
end $$;
create trigger documentation_new_state before insert on public.documentations for each row execute function documentation_private.guard_insert();
create function documentation_private.sync_tags() returns trigger language plpgsql security definer set search_path='' as $$
declare category text;values_json jsonb;tag_name text;tid bigint;
begin
 delete from public.documentation_tags where documentation_id=new.id;
 for category in select unnest(array['project','committee']) loop
  values_json:=new.details->case category when 'project' then 'projects' else 'committees' end;
  if values_json is null then continue;end if;
  if jsonb_typeof(values_json)<>'array' or jsonb_array_length(values_json)>40 then raise exception 'اختيارات المشاريع واللجان غير صالحة.';end if;
  for tag_name in select jsonb_array_elements_text(values_json) loop
   if tag_name like 'غير مرتبط%' then continue;end if;
   select id into tid from public.school_tags where kind=category and name=tag_name;
   if not found then raise exception 'اسم المشروع أو اللجنة غير معتمد: %',tag_name;end if;
   insert into public.documentation_tags values(new.id,tid) on conflict do nothing;
  end loop;
 end loop;
 return new;
end $$;
create trigger documentation_tag_relations after insert or update of details on public.documentations for each row execute function documentation_private.sync_tags();
create function documentation_private.trash_report(report_id bigint,deleted boolean,expected_version integer) returns jsonb language plpgsql security definer set search_path='' as $$
declare r public.documentations;name text;
begin
 if not documentation_private.can_manage() then raise exception 'الحذف والاستعادة متاحان للمديرة وحصه فقط.' using errcode='42501';end if;
 select * into r from public.documentations where id=report_id for update;
 if not found then raise exception 'التقرير غير موجود.';end if;
 if (r.deleted_at is not null)=deleted then return jsonb_build_object('id',r.id,'deleted',deleted,'version',r.deletion_version);end if;
 if r.deletion_version is distinct from expected_version then raise exception 'تغيرت حالة التقرير. حدّثي الصفحة.' using errcode='40001';end if;
 select full_name into name from public.profiles where id=auth.uid();
 update public.documentations set deleted_at=case when deleted then now() else null end,deleted_by=case when deleted then auth.uid() else null end,deleted_by_name=case when deleted then name else null end,deletion_version=deletion_version+1 where id=report_id;
 insert into public.documentation_deletion_log(documentation_id,actor_id,actor_name,action) values(report_id,auth.uid(),coalesce(name,'قيادة المدرسة'),case when deleted then 'delete' else 'restore' end);
 return jsonb_build_object('id',report_id,'deleted',deleted,'version',r.deletion_version+1);
end $$;
create function public.set_report_deleted(report_id bigint,deleted boolean,expected_version integer) returns jsonb language sql security invoker set search_path='' as $$select documentation_private.trash_report(report_id,deleted,expected_version)$$;
create function public.report_archive_context() returns jsonb language sql security invoker set search_path='' as $$select jsonb_build_object('can_manage',documentation_private.can_manage())$$;
-- Old reports keep their stored JSON relations; no batch rewrite/backfill of school records.
create function public.documentation_tag_memberships() returns table(documentation_id bigint,tag_id bigint) language sql stable security invoker set search_path='' as $$
 select l.documentation_id,l.tag_id from public.documentation_tags l
 union
 select d.id,t.id from public.documentations d join public.school_tags t on
 (t.kind='project' and (d.details->'projects' @> jsonb_build_array(t.name) or t.name=any(regexp_split_to_array(coalesce(d.projects,''),'\s*[•،\n]\s*')))) or
 (t.kind='committee' and (d.details->'committees' @> jsonb_build_array(t.name) or t.name=any(regexp_split_to_array(coalesce(d.committees,''),'\s*[•،\n]\s*'))))
$$;
